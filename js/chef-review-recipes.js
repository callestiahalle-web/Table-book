  function parseMinutes(value){
    const text=String(value||'').toLocaleLowerCase('ru-RU');
    const hours=Number(text.match(/(\d+(?:[.,]\d+)?)\s*(?:ч|час)/u)?.[1]?.replace(',','.')||0);
    const minutes=Number(text.match(/(\d+)\s*мин/u)?.[1]||0);
    return Math.max(0,Math.round(hours*60+minutes));
  }
  function formatMinutes(value){
    const total=Math.max(1,Math.round(value));
    if(total<60) return `${total} мин`;
    const h=Math.floor(total/60),m=total%60;
    return m?`${h} ч ${m} мин`:`${h} ч`;
  }
  function timingFor(recipe){
    const total=parseMinutes(recipe.totalTime||recipe.time)||30;
    let ratio=.3;
    if(['Салаты','Закуски','Соусы','Фрукты'].includes(recipe.category)) ratio=.55;
    else if(['Выпечка','Десерты'].includes(recipe.category)) ratio=.28;
    else if(recipe.category==='Су-вид') ratio=.12;
    const prep=Math.min(Math.max(5,Math.round(total*ratio/5)*5),Math.max(5,total-5),45);
    return {prepTime:formatMinutes(prep),cookTime:formatMinutes(Math.max(1,total-prep)),totalTime:formatMinutes(total)};
  }
  function normalizedStep(step){
    return String(step||'').normalize('NFKC').toLocaleLowerCase('ru-RU').replace(/ё/g,'е').replace(/[^\p{L}\p{N}]+/gu,' ').trim();
  }
  function dedupeSteps(steps){
    const seen=new Set();
    return (Array.isArray(steps)?steps:[]).filter(step=>{
      const key=normalizedStep(step);
      if(!key||seen.has(key)) return false;
      seen.add(key);
      return true;
    });
  }
  function applyIngredientFixes(recipe){
    const fixes=ingredientFixes[recipe.id];
    if(!fixes||!Array.isArray(recipe.ingredients)) return;
    recipe.ingredients=recipe.ingredients.flatMap(line=>fixes[line]||[line]);
  }
  function apply(recipes){
    recipes.forEach(recipe=>{
      const patch=exactPatches[recipe.id];
      if(patch) Object.assign(recipe,patch,{ingredients:patch.ingredients?[...patch.ingredients]:recipe.ingredients,steps:patch.steps?[...patch.steps]:recipe.steps});
      applyIngredientFixes(recipe);
      recipe.steps=dedupeSteps(recipe.steps);
      const timings=timingFor(recipe);
      recipe.prepTime=recipe.prepTime||timings.prepTime;
      recipe.cookTime=recipe.cookTime||timings.cookTime;
      recipe.totalTime=recipe.totalTime||recipe.time||timings.totalTime;
      recipe.historyNote=historyNotes[recipe.id]||recipe.historyNote||'';
      recipe.recipeSources=(countrySources[recipe.country]||[]).map(source=>({...source}));
      recipe.reviewVersion=REVIEW_VERSION;
    });
  }

